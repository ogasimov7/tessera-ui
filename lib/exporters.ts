const UTILS_SOURCE = `import { clsx, type ClassValue } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}
`;

/** npm packages imported by the shipped sources, plus what globals.css and lib/utils.ts need. */
export function kitDependencies(components: Record<string, string>) {
  const deps = new Set(["clsx", "tailwind-merge", "tw-animate-css"]);
  for (const src of Object.values(components)) {
    for (const [, spec] of src.matchAll(/from "([^"]+)"/g)) {
      if (spec === "react" || spec.startsWith("@/") || spec.startsWith(".")) continue;
      deps.add(spec);
    }
  }
  return [...deps].sort();
}

