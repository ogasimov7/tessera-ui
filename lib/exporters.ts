export function cssFor(sys: DesignSystem) {
  const block = (t: Palette) => KEYS.map((k) => `  --${k}: ${t[k]};`).join("\n");
  return `/* ${sys.name} · generated by Tessera UI (Tailwind CSS v4 + shadcn/ui) */
@import "tailwindcss";
@import "tw-animate-css";

@custom-variant dark (&:is(.dark *));

:root {
  --radius: ${sys.radius}rem;
${block(sys.light)}
}

.dark {
${block(sys.dark)}
}

@theme inline {
  --font-sans: ${fontStack(sys.fonts.body)};
  --font-heading: ${fontStack(sys.fonts.heading)};
  --font-mono: ${fontStack(sys.fonts.mono, "mono")};
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
${KEYS.map((k) => `  --color-${k}: var(--${k});`).join("\n")}
}

@layer base {
  * { @apply border-border outline-ring/50; }
  body { @apply bg-background text-foreground font-sans; }
  h1, h2, h3, h4 { @apply font-heading; }
}

/* Used by the Skeleton component. */
@keyframes tessera-shimmer { to { transform: translateX(100%); } }
`;
}

export function tokensJson(sys: DesignSystem) {
  const col = (t: Palette) => Object.fromEntries(KEYS.map((k) => [k, { $type: "color", $value: t[k] }]));
  return JSON.stringify(
    {
      $description: `${sys.name} design tokens (W3C DTCG format)`,
      color: { light: col(sys.light), dark: col(sys.dark) },
      radius: { base: { $type: "dimension", $value: `${sys.radius}rem` } },
      font: {
        heading: { $type: "fontFamily", $value: sys.fonts.heading },
        body: { $type: "fontFamily", $value: sys.fonts.body },
        mono: { $type: "fontFamily", $value: sys.fonts.mono },
      },
    },
    null,
    2,
  );
}

