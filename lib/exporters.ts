/**
 * All files in the download. `components` maps "components/ui/<name>.tsx" to source and `figma.plugin` is the
 * offline plugin source (lib/figma-plugin/builder.js + offline.js); the download route reads both from disk.
 */
export function buildFiles(
  sys: DesignSystem,
  plan: PlanId,
  components: Record<string, string>,
  figma: { code: string; plugin: string; pluginUrl?: string },
): Record<string, string> {
  const data = { name: sys.name, fonts: sys.fonts, radius: sys.radius, light: sys.light, dark: sys.dark };
  return {
    "README.md": readme(sys, plan, Object.keys(components).length, kitDependencies(components)),
    "LICENSE.md": license(sys, plan),
    "style-guide.html": styleGuide(sys, plan),
    "app/globals.css": cssFor(sys),
    "tokens.json": tokensJson(sys),
    "lib/utils.ts": UTILS_SOURCE,
    ...components,
    "figma/README.md": figmaReadme(sys, figma.code, figma.pluginUrl),
    "figma/offline-plugin/manifest.json": JSON.stringify(
      { name: `${sys.name} Import (offline)`, id: `tessera-import-${slug(sys.name)}`, api: "1.0.0", main: "code.js", editorType: ["figma"], documentAccess: "dynamic-page", networkAccess: { allowedDomains: ["none"] } },
      null,
      2,
    ),
    // A function replacer, so "$&" and friends in the data are not treated as replacement patterns.
    "figma/offline-plugin/code.js": figma.plugin.replace("__TESSERA_DATA__", () => JSON.stringify(data)),
  };
}
